// Release signing lives in android/key.properties (gitignored) and points at
// android/app/upload-keystore.jks (also gitignored). Back both up: losing the
// keystore means students can never update an installed copy of the app.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

